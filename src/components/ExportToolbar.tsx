export default function ExportToolbar({ dossier }: Props) {
  const [copiedMd, setCopiedMd] = useState(false);
  const [copiedJson, setCopiedJson] = useState(false);

  const handleCopyMarkdown = async () => {
    try {
      const md = generateDossierMarkdown(dossier);
      await navigator.clipboard.writeText(md);
      setCopiedMd(true);
      setTimeout(() => setCopiedMd(false), 2000);
    } catch {}
  };

  const handleDownloadDossier = () => {
    const md = generateDossierMarkdown(dossier);
    const blob = new Blob([md], { type: 'text/markdown;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `market-dossier-${dossier.meta.entities.industry.toLowerCase().replace(/[^a-z0-9]+/g, '-')}.md`;
    a.click();
    URL.revokeObjectURL(url);
  };

  const handleDownloadBrandContext = () => {
    const md = generateBrandContextMarkdown(dossier);
    const blob = new Blob([md], { type: 'text/markdown;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `brand-context.md`;
    a.click();
    URL.revokeObjectURL(url);
  };

  const handleCopyJson = async () => {
    try {
      await navigator.clipboard.writeText(JSON.stringify(dossier, null, 2));
      setCopiedJson(true);
      setTimeout(() => setCopiedJson(false), 2000);
    } catch {}
  };

  const handlePrint = () => {
    window.print();
  };

  return (
    <div className="flex flex-wrap items-center gap-2 print:hidden">
      {/* Download brand-context.md */}
      <button
        onClick={handleDownloadBrandContext}
        title="Download canonical brand-context.md"
        className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-bold bg-[#EFF6FF] hover:bg-[#DBEAFE] text-[#1862F6] border border-[#BFDBFE] transition cursor-pointer shadow-2xs"
      >
        <FileText className="w-3.5 h-3.5" />
        <span>brand-context.md</span>
      </button>

      {/* Download Full Dossier (.MD) */}
      <button
        onClick={handleDownloadDossier}
        title="Download Full Dossier as Markdown"
        className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-bold bg-white hover:bg-slate-50 text-slate-700 border border-slate-200 transition cursor-pointer shadow-2xs"
      >
        <Download className="w-3.5 h-3.5 text-slate-500" />
        <span>Download Dossier</span>
      </button>

      {/* Copy Markdown */}
      <button
        onClick={handleCopyMarkdown}
        title="Copy complete markdown to clipboard"
        className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-bold bg-white hover:bg-slate-50 text-slate-700 border border-slate-200 transition cursor-pointer shadow-2xs"
      >
        {copiedMd ? <Check className="w-3.5 h-3.5 text-emerald-600" /> : <Copy className="w-3.5 h-3.5 text-slate-500" />}
        <span>{copiedMd ? 'Copied' : 'Copy MD'}</span>
      </button>

      {/* Copy JSON */}
      <button
        onClick={handleCopyJson}
        title="Copy full JSON evidence to clipboard"
        className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-bold bg-white hover:bg-slate-50 text-slate-700 border border-slate-200 transition cursor-pointer shadow-2xs"
      >
        {copiedJson ? <Check className="w-3.5 h-3.5 text-emerald-600" /> : <Copy className="w-3.5 h-3.5 text-slate-500" />}
        <span>{copiedJson ? 'Copied JSON' : 'JSON'}</span>
      </button>

      {/* Print PDF */}
      <button
        onClick={handlePrint}
        title="Print or export as PDF"
        className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-bold bg-white hover:bg-slate-50 text-slate-700 border border-slate-200 transition cursor-pointer shadow-2xs"
      >
        <Printer className="w-3.5 h-3.5 text-slate-500" />
        <span>Print PDF</span>
      </button>
    </div>
  );
}
